/**
 * PG 集成测试：announcements 域（已迁移到 AsyncDb）。
 *
 * 只有在设置 `MC_PG_TEST_URL` 时才跑（默认 vitest 不连 PG，保持 sqlite 全绿）。
 * 本机会通过 SSH 隧道连 NAS 的 PG：
 *   1) node build/pg-migration/tunnel.mjs            # 15432 -> NAS 55432
 *   2) MC_PG_TEST_URL=postgres://microclass:***@127.0.0.1:15432/microclass_test \
 *      npx vitest run apps/api/test/pg-announcements.test.ts
 *
 * 每次运行都会重建 `announcements` 表，避免污染。
 */
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createPgAsyncDb, type AsyncDb } from '../src/db/async.js';
import { createPgPool } from '../src/db/pg/pool.js';
import { AnnouncementRepository } from '../src/db/repositories/announcementRepository.js';

const PG_URL = process.env.MC_PG_TEST_URL ?? '';
const enabled = PG_URL !== '';

describe.skipIf(!enabled)('announcements 仓储（PostgreSQL）', () => {
  let db: AsyncDb;
  let repo: AnnouncementRepository;

  beforeAll(async () => {
    db = createPgAsyncDb(createPgPool({ url: PG_URL, max: 2 }));
    await db.run('DROP TABLE IF EXISTS announcements');
    await db.run(`CREATE TABLE announcements (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title text NOT NULL,
      body text NOT NULL DEFAULT '',
      level text NOT NULL DEFAULT 'info',
      pinned bigint NOT NULL DEFAULT 0,
      published bigint NOT NULL DEFAULT 1,
      created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
      created_by bigint
    )`);
    repo = new AnnouncementRepository(db);
  });

  afterAll(async () => {
    await db.run('DROP TABLE IF EXISTS announcements');
    await db.close();
  });

  it('create 返回自增 id（INSERT ... RETURNING）', async () => {
    const id = await repo.create({
      title: 'PG 公告',
      body: 'hello',
      level: 'info',
      pinned: false,
      published: true,
      createdBy: 1,
    });
    expect(id).toBeGreaterThan(0);
    const row = await repo.findById(id);
    expect(row?.title).toBe('PG 公告');
  });

  it('update / remove 返回受影响行数', async () => {
    const id = await repo.create({
      title: '待改',
      body: '',
      level: 'warning',
      pinned: false,
      published: false,
      createdBy: 1,
    });
    const changed = await repo.update(id, {
      title: '已改',
      body: 'x',
      level: 'danger',
      pinned: true,
      published: true,
      createdBy: 1,
    });
    expect(changed).toBe(1);
    expect(await repo.remove(id)).toBe(1);
    expect(await repo.findById(id)).toBeUndefined();
  });

  it('listPublished 只出已发布，置顶优先', async () => {
    await repo.create({ title: '普通', body: '', level: 'info', pinned: false, published: true, createdBy: 1 });
    await repo.create({ title: '置顶', body: '', level: 'info', pinned: true, published: true, createdBy: 1 });
    await repo.create({ title: '草稿', body: '', level: 'info', pinned: false, published: false, createdBy: 1 });

    const list = await repo.listPublished(10);
    const titles = list.map((r) => r.title);
    expect(titles).toContain('置顶');
    expect(titles).not.toContain('草稿');
    expect(titles[0]).toBe('置顶');
  });

  it('listAll 分页与 countAll', async () => {
    const total = await repo.countAll();
    const page = await repo.listAll(1, 0);
    expect(page.length).toBe(1);
    expect(total).toBeGreaterThanOrEqual(3);
  });
});
